@app.post("/api/upload")
async def upload(file: UploadFile = File(...), sheet: str | None = Form(None), token: str = Depends(session_token)):
    path = _store_upload(file)
    try:
        df, meta = load_dataframe(path, sheet=sheet)
    except LoadError as exc:
        raise HTTPException(400, str(exc)) from exc
    except Exception as exc:  # noqa: BLE001
        raise HTTPException(400, f"Could not read file: {exc}") from exc
    finally:
        pass
    _check_limits(df)
    meta["file_name"] = os.path.basename(file.filename or "upload.csv")
    meta["upload_path"] = path if (meta.get("sheets") and len(meta["sheets"]) > 1) else None
    if not meta["upload_path"]:
        try:
            os.remove(path)
        except OSError:
            pass
    dataset_id = db.create_dataset(token, df, meta)
    return _dataset_payload(_get(dataset_id, token))


