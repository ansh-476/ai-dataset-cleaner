TOKEN_RE = re.compile(r"^[A-Za-z0-9_-]{16,64}$")

app = FastAPI(title="AI Dataset Cleaner", version="2.0")

origins = [o.strip() for o in settings.allowed_origins.split(",") if o.strip()]
app.add_middleware(
    CORSMiddleware,
    allow_origins=origins if origins != ["*"] else ["*"],
    allow_origin_regex=r"https://.*\.github\.io" if origins == ["*"] else None,
    allow_credentials=False,
    allow_methods=["*"],
    allow_headers=["*"],
    expose_headers=["Content-Disposition"],
)

JOBS: dict[str, PlanJob] = {}
_jobs_lock = threading.Lock()


@app.on_event("startup")
def _startup():
    db.init_db()
    try:
        removed = db.cleanup_old()
        if removed:
            print(f"[cleanup] removed {removed} datasets older than {settings.dataset_ttl_days} days")
    except Exception as exc:  # noqa: BLE001
        print("[cleanup] failed:", exc)

    def _periodic():
        while True:
            time.sleep(3600)
            try:
                db.cleanup_old()
                with _jobs_lock:   # forget finished jobs older than an hour
                    for jid in [j for j, job in JOBS.items() if job.status in ("done", "error") and time.time() - job.started > 3600]:
                        JOBS.pop(jid, None)
            except Exception:  # noqa: BLE001
                pass
    threading.Thread(target=_periodic, daemon=True).start()


