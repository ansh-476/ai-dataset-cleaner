@app.post("/api/datasets/{dataset_id}/validate")
async def validate_actions(dataset_id: str, payload: dict[str, Any], token: str = Depends(session_token)):
    ds = _get(dataset_id, token)
    out = []
    for a in payload.get("actions", []):
        a = normalize_action(a)
        out.append({"id": a["id"], "problems": validate_action(a, ds["current"])})
    return {"results": out}


@app.post("/api/datasets/{dataset_id}/apply")
async def apply(dataset_id: str, payload: dict[str, Any], token: str = Depends(session_token)):
    ds = _get(dataset_id, token)
    actions = payload.get("actions") or []
    if not actions:
        raise HTTPException(400, "No actions to apply.")
    if len(actions) > 300:
        raise HTTPException(400, "Too many actions (max 300).")
    plan = payload.get("plan") or {"id": None, "source": "user", "summary": "", "dataset_thinking": "",
                                   "column_thoughts": {}, "warnings": [], "model": None}
    before = _ensure_profile(ds)
    df_before = ds["current"]
    cleaned, log = apply_plan(df_before, actions)
    after = profile_dataframe(cleaned)
    entry = {"pass": len(ds["history"]) + 1, "applied_at": datetime.now().isoformat(timespec="seconds"),
             "plan": {k: v for k, v in plan.items() if k not in ("calls", "actions")} | {"actions": [normalize_action(a) for a in actions]},
             "log": log, "rows_before": int(len(df_before)), "rows_after": int(len(cleaned)),
             "cols_before": int(df_before.shape[1]), "cols_after": int(cleaned.shape[1]),
             "score_before": before["score"]["score"], "score_after": after["score"]["score"]}
    ds["history"].append(entry)
    ds["current"] = cleaned
    ds["profile"] = after
    db.save_dataset(ds, current=True, profile=True, history=True)
    return jsonable({"dataset_id": dataset_id, "log": log,
                     "profile_before": {"score": before["score"], "dataset": before["dataset"], "issue_count": len(before["issues"])},
                     "profile_after": after, "preview": preview_rows(cleaned),
                     "shape": {"rows": int(cleaned.shape[0]), "columns": int(cleaned.shape[1])},
                     "pass": entry["pass"], "history_entry": {k: v for k, v in entry.items() if k not in ("plan", "log")}})


@app.post("/api/datasets/{dataset_id}/reset")
def reset(dataset_id: str, token: str = Depends(session_token)):
    ds = _get(dataset_id, token)
    ds["current"] = ds["original"].copy()
    ds["profile"] = ds["profile_original"]
    ds["history"] = []
    db.save_dataset(ds, current=True, profile=True, history=True)
    return _dataset_payload(ds)


@app.get("/api/datasets/{dataset_id}/download")
def download(dataset_id: str, fmt: str = "csv", version: str = "current", token: str = Depends(session_token)):
    ds = _get(dataset_id, token)
    df = ds["original"] if version == "original" else ds["current"]
    base = os.path.splitext(ds["meta"].get("file_name", "dataset"))[0]
    suffix = "" if version == "original" else "_cleaned"
    if fmt == "xlsx":
        buf = io.BytesIO()
        out = df.copy()
        for c in out.columns:
            if pd.api.types.is_datetime64_any_dtype(out[c]) and getattr(out[c].dt, "tz", None) is not None:
                out[c] = out[c].dt.tz_localize(None)
        out.to_excel(buf, index=False)
        return Response(buf.getvalue(), media_type="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
                        headers={"Content-Disposition": f'attachment; filename="{base}{suffix}.xlsx"'})
    if fmt == "json":
        return Response(df.to_json(orient="records", indent=2, date_format="iso", force_ascii=False),
                        media_type="application/json", headers={"Content-Disposition": f'attachment; filename="{base}{suffix}.json"'})
    return Response(df.to_csv(index=False), media_type="text/csv",
                    headers={"Content-Disposition": f'attachment; filename="{base}{suffix}.csv"'})


@app.get("/api/datasets/{dataset_id}/report")
def report(dataset_id: str, fmt: str = "md", token: str = Depends(session_token)):
    ds = _get(dataset_id, token)
    _ensure_profile(ds)
    base = os.path.splitext(ds["meta"].get("file_name", "dataset"))[0]
    if fmt == "json":
        payload = jsonable({"file": ds["meta"], "created": ds["created"], "profile_original": ds["profile_original"],
                            "profile_current": ds["profile"], "history": ds["history"]})
        return Response(json.dumps(payload, indent=2, ensure_ascii=False), media_type="application/json",
                        headers={"Content-Disposition": f'attachment; filename="{base}_cleaning_report.json"'})
    return Response(build_markdown_report(ds), media_type="text/markdown",
                    headers={"Content-Disposition": f'attachment; filename="{base}_cleaning_report.md"'})


