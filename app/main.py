@app.post("/api/datasets/{dataset_id}/analyze")
def analyze(dataset_id: str, force: bool = False, token: str = Depends(session_token)):
    ds = _get(dataset_id, token)
    if force:
        ds["profile"] = None
    profile = _ensure_profile(ds)
    return {"dataset_id": dataset_id, "profile": profile, "pass": len(ds["history"]) + 1,
            "last_plan": ds.get("last_plan")}


@app.post("/api/datasets/{dataset_id}/plan")
async def start_plan(dataset_id: str, payload: dict[str, Any] | None = None, token: str = Depends(session_token)):
    ds = _get(dataset_id, token)
    profile = _ensure_profile(ds)
    with _jobs_lock:
        running = [j for j in JOBS.values() if j.status in ("queued", "running")]
        if any(j.dataset_id == dataset_id for j in running):
            raise HTTPException(409, "A plan is already being generated for this dataset.")
        if len([j for j in running if j.session_token == token]) >= 1:
            raise HTTPException(429, "You already have a plan in progress - wait for it to finish.")
        if len(running) >= settings.max_concurrent_jobs:
            raise HTTPException(429, "The server is busy planning other datasets - try again in a minute.")
    # per-job options (safe to expose in hosted mode)
    opts = payload or {}
    job_settings = copy.copy(settings)
    for k in ("columns_per_call", "include_clean_columns", "summarize_plan"):
        if k in opts and opts[k] is not None:
            job_settings.update(**{k: opts[k]})
    job_settings.columns_per_call = max(1, min(int(job_settings.columns_per_call), 10))
    job = PlanJob(dataset_id, profile, [str(c) for c in ds["current"].columns], ds["meta"].get("file_name", "dataset"), job_settings)
    job.session_token = token

    def _persist(j: PlanJob):
        try:
            d = db.load_dataset(j.dataset_id, token)
            if d and j.plan:
                d["last_plan"] = {k: v for k, v in j.plan.items() if k != "calls"}
                db.save_dataset(d, plan=True)
        except Exception:  # noqa: BLE001
            pass
    job.on_done = _persist
    with _jobs_lock:
        JOBS[job.id] = job
    job.start()
    return {"job_id": job.id}


