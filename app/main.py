@app.post("/api/settings")
async def set_settings(payload: dict[str, Any]):
    """Local mode only: change provider/model/key at runtime. Hosted mode exposes only plan options per job."""
    if not settings.allow_client_settings:
        raise HTTPException(403, "Settings are fixed on this server (set them as environment variables).")
    allowed = {"provider", "api_key", "model", "base_url", "temperature", "num_ctx", "request_timeout",
               "columns_per_call", "include_clean_columns", "summarize_plan", "allow_rule_fallback"}
    clean = {k: v for k, v in payload.items() if k in allowed}
    if clean.get("api_key") == "set":
        clean.pop("api_key")
    if "provider" in clean and clean["provider"] not in PROVIDER_DEFAULTS:
        raise HTTPException(400, f"Unknown provider. Choose one of {list(PROVIDER_DEFAULTS)}")
    if "provider" in clean and clean["provider"] != settings.provider:
        # switching provider resets model/base_url to that provider's defaults unless given
        clean.setdefault("model", "")
        clean.setdefault("base_url", "")
    settings.update(**clean)
    return _public_settings()


