@app.post("/api/datasets/{dataset_id}/sheet")
async def change_sheet(dataset_id: str, payload: dict[str, Any], token: str = Depends(session_token)):
    ds = _get(dataset_id, token)
    path = ds["meta"].get("upload_path")
    if not path or not os.path.exists(path):
        raise HTTPException(400, "The original Excel file is no longer available; upload it again to pick another sheet.")
    try:
        df, meta = load_dataframe(path, sheet=payload.get("sheet"))
    except LoadError as exc:
        raise HTTPException(400, str(exc)) from exc
    _check_limits(df)
    meta["file_name"] = ds["meta"].get("file_name")
    meta["upload_path"] = path
    ds.update(original=df, current=df.copy(), meta=meta, profile=None, profile_original=None, history=[])
    db.save_dataset(ds, original=True, current=True, meta=True, profile=True, history=True)
    return _dataset_payload(ds)


