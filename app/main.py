def session_token(x_session_token: str | None = Header(default=None), s: str | None = Query(default=None)) -> str:
    token = x_session_token or s
    if not token or not TOKEN_RE.match(token):
        raise HTTPException(401, "Missing or invalid session token. Reload the page to get a new session.")
    return token


def _get(dataset_id: str, token: str) -> dict[str, Any]:
    ds = db.load_dataset(dataset_id, token)
    if not ds:
        raise HTTPException(404, "Dataset not found (it may have expired or belongs to another session).")
    return ds


def _dataset_payload(ds: dict[str, Any]) -> dict[str, Any]:
    cur = ds["current"]
    return jsonable({
        "dataset_id": ds["id"], "meta": ds["meta"], "preview": preview_rows(cur),
        "shape": {"rows": int(cur.shape[0]), "columns": int(cur.shape[1])},
        "original_shape": {"rows": int(ds["original"].shape[0]), "columns": int(ds["original"].shape[1])},
        "passes": len(ds["history"]), "has_profile": ds["profile"] is not None,
        "created": ds.get("created"), "updated": ds.get("updated"),
    })


def _ensure_profile(ds: dict[str, Any]) -> dict[str, Any]:
    if ds["profile"] is None:
        ds["profile"] = profile_dataframe(ds["current"])
        if ds["profile_original"] is None:
            ds["profile_original"] = ds["profile"]
        db.save_dataset(ds, profile=True)
    return ds["profile"]


def _check_limits(df: pd.DataFrame):
    if df.shape[1] == 0:
        raise HTTPException(400, "The file has no columns.")
    if df.shape[0] > settings.max_rows:
        raise HTTPException(413, f"Too many rows ({df.shape[0]:,}). The limit on this server is {settings.max_rows:,} rows.")
    if df.shape[1] > settings.max_columns:
        raise HTTPException(413, f"Too many columns ({df.shape[1]}). The limit is {settings.max_columns}.")


def _store_upload(upload: UploadFile) -> str:
    name = os.path.basename(upload.filename or "upload.csv")
    ext = os.path.splitext(name)[1].lower()
    if ext not in SUPPORTED_EXTENSIONS:
        raise HTTPException(400, f"Unsupported file type '{ext}'. Use CSV, TSV, TXT, XLSX, XLS or JSON.")
    path = os.path.join(settings.upload_dir, f"{uuid.uuid4().hex[:8]}_{name}")
    limit = settings.max_upload_mb * 1024 * 1024
    size = 0
    with open(path, "wb") as fh:
        while True:
            chunk = upload.file.read(1024 * 1024)
            if not chunk:
                break
            size += len(chunk)
            if size > limit:
                fh.close()
                os.remove(path)
                raise HTTPException(413, f"File is larger than {settings.max_upload_mb} MB.")
            fh.write(chunk)
    return path


def _public_settings() -> dict[str, Any]:
    d = settings.to_dict(public=True)
    d["hosted"] = not settings.allow_client_settings
    d["providers"] = list(PROVIDER_DEFAULTS)
    return d


